// Command default-annotations-gen scans Terraform modules and, for each module, emits a
// default_annotations.gen.tf that binds a set of Scaleway annotation values to every
// scaleway_* resource defined in that module.
//
// The user is expected to create the annotation keys and values themselves.
// This tool only generates the scaleway_annotations_binding fan-out: for each
// (value, target) pair it produces one binding, so N values x M targets =>
// N*M bindings.
//
// Values are the scaleway_annotations_value resources declared in the module
// (auto-discovered) plus any explicit -value expressions passed on the command
// line. Targets are all other scaleway_* resources (scaleway_annotations_* are
// excluded).
//
// With -inherit, a module that declares the -inherit-var variable (a
// map(string) of key => value_id) is treated as a consumer: its default_annotations values
// are read from that variable instead of local resources, so a parent module
// can pass its annotation values down to child modules.
//
// The path is walked recursively: every directory that directly contains at
// least one .tf file is treated as a Terraform module and gets its own
// default_annotations.gen.tf.
package main

import (
	"flag"
	"fmt"
	"io/fs"
	"log"
	"math/big"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/hashicorp/hcl/v2"
	"github.com/hashicorp/hcl/v2/hclparse"
	"github.com/hashicorp/hcl/v2/hclsyntax"
	"github.com/zclconf/go-cty/cty"
)

const (
	providerPrefix      = "scaleway_"
	annotationsPrefix   = "scaleway_annotations_"
	annotationValueType = "scaleway_annotations_value"
	bindingResource     = "scaleway_annotations_binding"
	genName             = "default_annotations"
	targetRefAttr       = "srn"
	valueRefAttr        = "value_id"
	outputFileName      = "default_annotations.gen.tf"
	header              = "# Code generated by cmd/default-annotations-gen; DO NOT EDIT."
)

// bindingsLocal is the static annotations_bindings local emitted in every
// generated file.
const bindingsLocal = `  annotations_bindings = {
    for entry in flatten([
      for v_key, v_id in local.annotations_values :
      [
        for t_key, t_srn in local.annotations_targets :
        {
          key        = "${v_key}|${t_key}"
          value_id   = v_id
          target_srn = t_srn
        }
      ]
    ])
    : entry.key => {
      value_id   = entry.value_id
      target_srn = entry.target_srn
    }
  }
`

// resourceRef is a single discovered scaleway_* resource instance.
type resourceRef struct {
	Type       string
	Name       string
	SetCount   int
	IsSet      bool
	SetCountOK bool
}

// refEntry is one bindable reference: a stable known for_each key and the HCL
// expression that yields the value.
type refEntry struct {
	Key  string
	Expr string
}

func main() {
	var values stringSlice

	write := flag.Bool("write", false, "write default_annotations.gen.tf into each module (default: print to stdout)")
	check := flag.Bool("check", false, "exit non-zero if any default_annotations.gen.tf is out of date")
	path := flag.String("path", "", "terraform module directory to walk recursively (required)")

	flag.Var(&values, "value", "annotation value to bind (resource ref or value_id expression, repeatable)")

	inherit := flag.Bool("inherit", false, "treat a module that declares -inherit-var as a consumer receiving the annotation values from that variable")
	inheritVar := flag.String("inherit-var", "default_annotations_values", "variable (map(string)) carrying inherited annotation values, used with -inherit")

	flag.Parse()

	if *path == "" {
		log.Fatal("-path is required")
	}

	if *check && *write {
		log.Fatal("-check and -write are mutually exclusive")
	}

	explicit := explicitValues(values)

	dirs, err := findModuleDirs(*path)
	if err != nil {
		log.Fatalf("scan %q: %v", *path, err)
	}

	updated, stale, skipped := 0, 0, 0

	for _, dir := range dirs {
		content, err := generateModule(dir, explicit, *inherit, *inheritVar)
		if err != nil {
			log.Printf("%s: %v", dir, err)

			continue
		}

		if *check {
			ok, cerr := checkModule(dir, content)
			if cerr != nil {
				log.Printf("%s: %v", dir, cerr)

				continue
			}

			if ok {
				if content == "" {
					skipped++
				} else {
					updated++
				}

				continue
			}

			log.Printf("stale: %s", dir)

			stale++

			continue
		}

		if content == "" {
			skipped++

			continue
		}

		if err := emit(dir, content, *write); err != nil {
			log.Printf("%s: %v", dir, err)

			continue
		}

		updated++
	}

	if *check {
		log.Printf("%d module(s) in sync, %d skipped, %d stale", updated, skipped, stale)

		if stale > 0 {
			os.Exit(1)
		}

		return
	}

	log.Printf("%d module(s) generated, %d skipped", updated, skipped)
}

func emit(module, content string, write bool) error {
	if write {
		return os.WriteFile(filepath.Join(module, outputFileName), []byte(content), 0o600)
	}

	_, err := fmt.Fprintf(os.Stdout, "==== %s ====\n%s\n", module, content)

	return err
}

// checkModule reports whether the generated file for dir is in sync with the
// expected content. Empty content means no file is expected.
func checkModule(dir, content string) (bool, error) {
	file := filepath.Join(dir, outputFileName)
	existing, err := os.ReadFile(file) //nolint: gosec // G304: path is a module dir under -path, not user input

	if os.IsNotExist(err) {
		return content == "", nil
	}

	if err != nil {
		return false, err
	}

	return content != "" && string(existing) == content, nil
}

// stringSlice accumulates repeated flags.
type stringSlice []string

func (s *stringSlice) String() string { return strings.Join(*s, ", ") }

func (s *stringSlice) Set(v string) error {
	*s = append(*s, v)

	return nil
}

// explicitValues turns -value arguments into ref entries. A bare resource
// reference (type.name) is expanded to its .value_id; anything with two or
// more dots is used verbatim.
func explicitValues(vals []string) []refEntry {
	out := make([]refEntry, 0, len(vals))

	for _, v := range vals {
		expr := normalizeValueExpr(v)
		out = append(out, refEntry{Key: expr, Expr: expr})
	}

	return out
}

func normalizeValueExpr(s string) string {
	if strings.Count(s, ".") >= 2 {
		return s
	}

	return s + "." + valueRefAttr
}

// findModuleDirs walks root recursively and returns every directory that
// directly contains at least one .tf file, in sorted order. Hidden directories
// (e.g. .terraform) are skipped.
func findModuleDirs(root string) ([]string, error) {
	seen := make(map[string]bool)

	var dirs []string

	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if d.IsDir() {
			if path != root && isHidden(path) {
				return filepath.SkipDir
			}

			return nil
		}

		if !strings.HasSuffix(d.Name(), ".tf") {
			return nil
		}

		dir := filepath.Dir(path)
		if !seen[dir] {
			seen[dir] = true
			dirs = append(dirs, dir)
		}

		return nil
	})
	if err != nil {
		return nil, err
	}

	sort.Strings(dirs)

	return dirs, nil
}

func isHidden(path string) bool {
	for part := range strings.SplitSeq(filepath.ToSlash(path), "/") {
		if strings.HasPrefix(part, ".") && part != "." && part != ".." {
			return true
		}
	}

	return false
}

func generateModule(dir string, explicit []refEntry, inherit bool, inheritVar string) (string, error) {
	refs, err := collectResources(dir)
	if err != nil {
		return "", err
	}

	if len(refs) == 0 {
		return "", nil
	}

	sort.Slice(refs, func(i, j int) bool {
		if refs[i].Type != refs[j].Type {
			return refs[i].Type < refs[j].Type
		}

		return refs[i].Name < refs[j].Name
	})

	values, targets, warnings := buildRefs(refs)
	values = mergeRefEntries(values, explicit)
	valuesExpr := ""

	if inherit && declaresVariable(dir, inheritVar) {
		values = nil
		valuesExpr = "var." + inheritVar
	}

	if (valuesExpr == "" && len(values) == 0) || len(targets) == 0 {
		return "", nil
	}

	return renderModule(valuesExpr, values, targets, warnings), nil
}

// buildRefs splits discovered resources into annotation values and bindable
// targets. scaleway_annotations_value resources become values; every other
// scaleway_* resource (except scaleway_annotations_*) becomes a target.
func buildRefs(refs []resourceRef) (values, targets []refEntry, warnings []string) {
	for _, r := range refs {
		base := r.Type + "." + r.Name
		isValue := r.Type == annotationValueType

		if !isValue && strings.HasPrefix(r.Type, annotationsPrefix) {
			continue
		}

		attr := targetRefAttr
		dest := &targets

		if isValue {
			attr = valueRefAttr
			dest = &values
		}

		switch {
		case !r.IsSet:
			*dest = append(*dest, makeEntry(base, attr, isValue, -1))
		case r.SetCountOK && r.SetCount > 0:
			for i := range r.SetCount {
				*dest = append(*dest, makeEntry(base, attr, isValue, i))
			}
		default:
			warnings = append(warnings, "# NOTE: skipped "+base+": count/for_each size is not a literal; enumerate instances manually")
		}
	}

	return values, targets, warnings
}

// makeEntry builds the refEntry for one instance of a resource. A negative idx
// means the resource is not indexed (no count / for_each).
func makeEntry(base, attr string, isValue bool, idx int) refEntry {
	key := base
	expr := base

	if idx >= 0 {
		key += fmt.Sprintf(".%d", idx)
		expr = fmt.Sprintf("%s[%d]", base, idx)
	}

	expr += "." + attr

	if isValue {
		key += "." + attr
	}

	return refEntry{Key: key, Expr: expr}
}

func mergeRefEntries(base, extra []refEntry) []refEntry {
	seen := make(map[string]bool, len(base)+len(extra))
	out := make([]refEntry, 0, len(base)+len(extra))

	for _, e := range append(base, extra...) {
		if !seen[e.Key] {
			seen[e.Key] = true
			out = append(out, e)
		}
	}

	return out
}

func alignedMapEntries(entries []refEntry) string {
	maxw := 0

	for _, e := range entries {
		if w := len(e.Key) + 2; w > maxw {
			maxw = w
		}
	}

	var s strings.Builder

	for _, e := range entries {
		s.WriteString(fmt.Sprintf("    %-*s = %s\n", maxw, fmt.Sprintf("%q", e.Key), e.Expr))
	}

	return s.String()
}

// renderValues renders the annotations_values local: either an inherited variable
// expression (a map(string)) or a literal map of discovered value expressions.
func renderValues(valuesExpr string, values []refEntry) string {
	if valuesExpr != "" {
		return "  annotations_values = " + valuesExpr + "\n\n"
	}

	return "  annotations_values = {\n" + alignedMapEntries(values) + "  }\n\n"
}

func renderModule(valuesExpr string, values, targets []refEntry, warnings []string) string {
	var b strings.Builder
	b.WriteString(header + "\n")

	for _, w := range warnings {
		b.WriteString(w + "\n")
	}

	if len(warnings) > 0 {
		b.WriteString("\n")
	}

	b.WriteString("locals {\n")
	b.WriteString(renderValues(valuesExpr, values))
	b.WriteString("  annotations_targets = {\n")
	b.WriteString(alignedMapEntries(targets))
	b.WriteString("  }\n\n")
	b.WriteString(bindingsLocal)
	b.WriteString("}\n\n")

	b.WriteString(fmt.Sprintf("resource %q %q {\n", bindingResource, genName))
	b.WriteString("  for_each = local.annotations_bindings\n\n")
	b.WriteString("  value_id   = each.value.value_id\n")
	b.WriteString("  target_srn = each.value.target_srn\n")
	b.WriteString("}\n")

	return b.String()
}

// moduleFiles returns the module's .tf files, sorted, excluding the generated
// file.
func moduleFiles(dir string) ([]string, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.tf"))
	if err != nil {
		return nil, err
	}

	sort.Strings(files)

	var out []string

	for _, f := range files {
		if filepath.Base(f) != outputFileName {
			out = append(out, f)
		}
	}

	return out, nil
}

// declaresVariable reports whether the module declares a variable with the
// given name in any of its .tf files (the generated file is ignored).
func declaresVariable(dir, name string) bool {
	files, err := moduleFiles(dir)
	if err != nil {
		return false
	}

	p := hclparse.NewParser()

	for _, file := range files {
		parsed, diags := p.ParseHCLFile(file)
		if parsed == nil || diags.HasErrors() {
			continue
		}

		body, ok := parsed.Body.(*hclsyntax.Body)
		if !ok {
			continue
		}

		for _, block := range body.Blocks {
			if block.Type == "variable" && len(block.Labels) == 1 && block.Labels[0] == name {
				return true
			}
		}
	}

	return false
}

func collectResources(dir string) ([]resourceRef, error) {
	files, err := moduleFiles(dir)
	if err != nil {
		return nil, err
	}

	p := hclparse.NewParser()

	var refs []resourceRef

	for _, file := range files {
		parsed, diags := p.ParseHCLFile(file)
		if parsed == nil {
			continue
		}

		if diags.HasErrors() {
			log.Printf("parse %s: %s", file, diags.Error())
		}

		refs = append(refs, fileResources(parsed)...)
	}

	return refs, nil
}

func fileResources(f *hcl.File) []resourceRef {
	body, ok := f.Body.(*hclsyntax.Body)
	if !ok {
		return nil
	}

	var refs []resourceRef

	for _, block := range body.Blocks {
		if block.Type != "resource" || len(block.Labels) < 2 {
			continue
		}

		if !strings.HasPrefix(block.Labels[0], providerPrefix) {
			continue
		}

		ref := resourceRef{
			Type:  block.Labels[0],
			Name:  block.Labels[1],
			IsSet: hasSetAttr(block),
		}

		if ref.IsSet {
			ref.SetCount, ref.SetCountOK = literalCount(block)
		}

		refs = append(refs, ref)
	}

	return refs
}

func hasSetAttr(block *hclsyntax.Block) bool {
	_, hasForEach := block.Body.Attributes["for_each"]
	_, hasCount := block.Body.Attributes["count"]

	return hasForEach || hasCount
}

// literalCount returns the value of a `count` attribute when it is a literal
// non-negative integer. Dynamic counts (variables, for_each) return ok=false.
func literalCount(block *hclsyntax.Block) (int, bool) {
	attr, ok := block.Body.Attributes["count"]
	if !ok {
		return 0, false
	}

	val, diags := attr.Expr.Value(&hcl.EvalContext{})
	if diags.HasErrors() || !val.IsKnown() || val.Type() != cty.Number {
		return 0, false
	}

	n, acc := val.AsBigFloat().Int64()
	if acc != big.Exact {
		return 0, false
	}

	return int(n), true
}
